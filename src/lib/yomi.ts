/**
 * 九九の読み（唱え方）テーブル。
 *
 * 風呂に貼ってある九九シートと同じ「唱えて覚える」形式に合わせる。
 * 問題は聞き取りやすい平読み（例: ろく かける なな）で読み上げ、
 * 答えは九九の唱え方（例: ろくしちしじゅうに）で読み上げる。
 * 答えの側を唱え方にすることで、覚える対象そのものが耳に入る。
 */

/** 問題読み上げ用の平読み。し／しち／く より よん／なな／きゅう の方が小 2 には明瞭。 */
const PLAIN_DIGIT = ['', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう'] as const

/** 九九の掛け合わせ部分。行が掛けられる数、列が掛ける数（ともに 1〜9）。 */
const KUKU_PAIR: readonly (readonly string[])[] = [
  ['いんいち', 'いんに', 'いんさん', 'いんし', 'いんご', 'いんろく', 'いんしち', 'いんはち', 'いんく'],
  ['にいち', 'ににん', 'にさん', 'にし', 'にご', 'にろく', 'にしち', 'にはち', 'にく'],
  ['さんいち', 'さんに', 'さざん', 'さんし', 'さんご', 'さぶろく', 'さんしち', 'さんぱ', 'さんく'],
  ['しいち', 'しに', 'しさん', 'しし', 'しご', 'しろく', 'ししち', 'しは', 'しく'],
  ['ごいち', 'ごに', 'ごさん', 'ごし', 'ごご', 'ごろく', 'ごしち', 'ごは', 'ごっく'],
  ['ろくいち', 'ろくに', 'ろくさん', 'ろくし', 'ろくご', 'ろくろく', 'ろくしち', 'ろくは', 'ろっく'],
  ['しちいち', 'しちに', 'しちさん', 'しちし', 'しちご', 'しちろく', 'しちしち', 'しちは', 'しちく'],
  ['はちいち', 'はちに', 'はちさん', 'はちし', 'はちご', 'はちろく', 'はちしち', 'はっぱ', 'はっく'],
  ['くいち', 'くに', 'くさん', 'くし', 'くご', 'くろく', 'くしち', 'くは', 'くく'],
]

/** 積の読み。1 桁の積は「が」を伴う（例: 二三が六）。 */
const KUKU_PRODUCT: Readonly<Record<number, string>> = {
  1: 'がいち', 2: 'がに', 3: 'がさん', 4: 'がし', 5: 'がご',
  6: 'がろく', 7: 'がしち', 8: 'がはち', 9: 'がく',
  10: 'じゅう', 12: 'じゅうに', 14: 'じゅうし', 15: 'じゅうご', 16: 'じゅうろく',
  18: 'じゅうはち', 20: 'にじゅう', 21: 'にじゅういち', 24: 'にじゅうし', 25: 'にじゅうご',
  27: 'にじゅうしち', 28: 'にじゅうはち', 30: 'さんじゅう', 32: 'さんじゅうに', 35: 'さんじゅうご',
  36: 'さんじゅうろく', 40: 'しじゅう', 42: 'しじゅうに', 45: 'しじゅうご', 48: 'しじゅうはち',
  49: 'しじゅうく', 54: 'ごじゅうし', 56: 'ごじゅうろく', 63: 'ろくじゅうさん', 64: 'ろくじゅうし',
  72: 'しちじゅうに', 81: 'はちじゅういち',
}

/** 問題の読み上げ文。例: (6, 7) -> 「ろく かける なな」 */
export function questionYomi(a: number, b: number): string {
  return `${PLAIN_DIGIT[a]} かける ${PLAIN_DIGIT[b]}`
}

/** 答えの読み上げ文（九九の唱え方）。例: (6, 7) -> 「ろくしちしじゅうに」 */
export function answerYomi(a: number, b: number): string {
  const pair = KUKU_PAIR[a - 1]?.[b - 1]
  const product = KUKU_PRODUCT[a * b]
  if (!pair || !product) return `${a} かける ${b} は ${a * b}`
  return pair + product
}

/** 段の呼び名。例: 5 -> 「ごのだん」 */
export function stageYomi(stage: number): string {
  return `${PLAIN_DIGIT[stage]}のだん`
}
